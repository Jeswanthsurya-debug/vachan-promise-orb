/* ───────── fonts: the right Noto family for each script ───────── */

export const SCRIPT_FONT: Record<string, string> = {
  "hi-IN": "Noto Sans Devanagari",
  "mr-IN": "Noto Sans Devanagari",
  "ta-IN": "Noto Sans Tamil",
  "te-IN": "Noto Sans Telugu",
  "kn-IN": "Noto Sans Kannada",
  "bn-IN": "Noto Sans Bengali",
};

export const ALL_NOTO = [
  "Noto Sans Devanagari",
  "Noto Sans Tamil",
  "Noto Sans Telugu",
  "Noto Sans Kannada",
  "Noto Sans Bengali",
];

/**
 * CSS font-family for a language: its own Noto font first, then Inter, then every other
 * Noto script (so text typed in a DIFFERENT script than the selected language still renders).
 */
export function fontStack(lang: string): string {
  const own = SCRIPT_FONT[lang];
  const names = [own, "Inter", ...ALL_NOTO.filter((f) => f !== own), "Noto Sans"].filter(Boolean) as string[];
  return names.map((n) => `"${n}"`).join(", ") + ", system-ui, sans-serif";
}

/** Value for the HTML `lang` attribute. */
export function htmlLang(lang: string): string {
  return lang === "hi-en" ? "hi-Latn" : lang;
}

/** Locale for the browser's SpeechRecognition (Hinglish speakers are recognised as Hindi). */
export function recognitionLocale(lang: string): string {
  return lang === "hi-en" ? "hi-IN" : lang;
}
